// プレイヤーの呼び名と、エンジンが作った文の言い換え（画面に出す言葉だけ。ルールの処理には関係ない）
// エンジンの文は「P1」「P2」でプレイヤーを書くので、画面に出す前に呼び名（あなた／CPU、プレイヤー1／プレイヤー2）に置きかえる。
// 置きかえはすべてこのファイルの関数を通す（記録・勝ち負けの理由・結果の欄・「できません」の知らせ）。

/** プレイヤーの呼び名：CPU対戦では「あなた」（P1）と「CPU」（P2）、2人対戦では「プレイヤー1」「プレイヤー2」（MASTERの決定） */
export const playerName = (p, cpu) => (cpu ? (p === 0 ? 'あなた' : 'CPU') : `プレイヤー${p + 1}`);

/** 勝ち負けの短い言葉：CPU対戦・オンライン対戦では「あなたの勝ち／あなたの負け」（me＝自分の席）、2人対戦では「プレイヤー1の勝利」 */
export const resultText = (winner, cpu, me = 0) => (winner === 'draw' ? '引き分け' : cpu ? (winner === me ? 'あなたの勝ち' : 'あなたの負け') : `${playerName(winner, false)}の勝利`);

/** 相手の呼び方：CPU対戦では「CPU」、2人対戦では「相手」 */
export const oppWord = cpu => (cpu ? 'CPU' : '相手');

/**
 * エンジンが作った文を、画面の言葉に置きかえる。
 * 「P1」「P2」→ 呼び名、「サレンダー」→「降参」（MASTERの決定。エンジンの文と、戦績の「サレンダー」の見分けはそのまま）
 */
export const whoText = (text, cpu) => String(text ?? '')
  // CPU対戦の勝ち負けは、ほかの所（帯・結果）と同じ「あなたの勝ち／あなたの負け」に
  .replace(/P([12])の勝利/g, (m, k) => (cpu ? (k === '1' ? 'あなたの勝ち' : 'あなたの負け') : m))
  .replace(/P([12])(?!\d)/g, (_, n) => playerName(Number(n) - 1, cpu))
  .replace(/サレンダー/g, '降参');

/**
 * オンライン対戦の言い換え：「P1」「P2」→ names[0]・names[1]（自分は「あなた」、相手は相手の名前）。
 * 「P○の勝利」は、自分の席 me から見た「あなたの勝ち／あなたの負け」。「サレンダー」→「降参」
 */
export const whoNames = (text, names, me = 0) => String(text ?? '')
  .replace(/P([12])の勝利/g, (m, k) => (Number(k) - 1 === me ? 'あなたの勝ち' : 'あなたの負け'))
  .replace(/P([12])(?!\d)/g, (_, k) => names[Number(k) - 1])
  .replace(/サレンダー/g, '降参');
