/** 台詞を1つ選ぶ */
export function lineFor(deckCode, kind, vars = {}) {
  const set = LINES[deckCode]?.[kind] ?? GENERIC[kind];
  const list = set && set.length ? set : GENERIC[kind];
  const t = list[Math.floor(Math.random() * list.length)];
  return t.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
