export const PERSONA_KEYS = Object.keys(PERSONAS);
export const randomPersona = () => PERSONA_KEYS[Math.floor(Math.random() * PERSONA_KEYS.length)];

/** 効果の短い説明を、性格の口調の文にする（「①：」などの番号は外し、名詞で終わる時は「する」を足す） */
export function effectLine(persona, label) {
  let t = String(label || '').replace(/^[①-⑳]+[：:]\s*/, '').replace(/（[^）]*）/g, '').trim();
  if (!t) return '';
  if (/[一-龯ー]$/.test(t)) t += 'する';
  const end = (PERSONAS[persona] || PERSONAS.hot).end;
  return t + end;
}

/** 台詞を1つ選ぶ */
export function lineFor(persona, kind, vars = {}) {
  const P = PERSONAS[persona] || PERSONAS.hot;
  const list = P[kind];
  if (!list || !list.length) return '';
  const t = list[Math.floor(Math.random() * list.length)];
  return t.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}
